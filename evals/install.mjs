import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fixture, buildBundle, feedback, save, read, lens, hash } from './lib/fixtures.mjs';
import { install } from '../scripts/install-wiki-module.mjs';
import { readWiki } from '../scripts/lib/wiki-read.mjs';
import { validateChangeSet } from '../scripts/validate-change-set.mjs';

const root = mkdtempSync(join(tmpdir(), 'method-wiki-install-'));
let checks = 0;
const check = (name, action) => { action(); checks += 1; console.log(`PASS ${name}`); };
try {
  const fix = fixture(join(root, 'new'), { withRecipe: true });
  check('no fixed operation or page count', () => assert.equal(validateChangeSet(fix.set).valid, true));
  const bundle = buildBundle(fix);
  const approval = feedback(fix, bundle);
  check('dry run has no writes', () => { const result = install(fix.bundlePath, fix.feedbackPath, fix.wiki, { dryRun: true, reportOutput: join(root, 'ignored.json') }); assert.equal(result.status, 'preflight_ok'); assert.equal(existsSync(fix.wiki), false); assert.equal(existsSync(join(root, 'ignored.json')), false); });
  let result;
  check('new library installs without stage receipts', () => { result = install(fix.bundlePath, fix.feedbackPath, fix.wiki, { reportOutput: join(fix.root, 'install-report.json') }); assert.equal(result.status, 'installed'); assert.equal(readWiki(fix.wiki).wiki_root_sha256, result.wiki_root_sha256); assert.equal(readWiki(fix.wiki).recipeCatalog.recipes.length, 1); });
  check('provenance maps source IDs and real files', () => { const data = read(join(fix.wiki, 'revisions', result.approval_id, 'provenance.json')); assert.equal(data.mappings[0].source_id, 'source-method'); assert.equal(data.mappings[0].origin.sha256, hash(readFileSync(join(fix.root, 'source.md')))); });
  check('same approval is idempotent', () => { const before = readWiki(fix.wiki).wiki_root_sha256; assert.equal(install(fix.bundlePath, fix.feedbackPath, fix.wiki).status, 'already_installed'); assert.equal(readWiki(fix.wiki).wiki_root_sha256, before); });
  const upgrade = fixture(join(root, 'upgrade'));
  upgrade.set.wiki_dir = fix.wiki; upgrade.wiki = fix.wiki;
  upgrade.set.route = 'upgrade_existing'; upgrade.set.baseline_sha256 = readWiki(fix.wiki).wiki_root_sha256;
  upgrade.set.modules = [];
  upgrade.set.changes[0].object = lens('lens_new-proof');
  upgrade.set.changes[0].comparison = { matched_ids: ['lens_compare-value'], rationale_zh: '新增检验边界' };
  save(upgrade.changeSet, upgrade.set);
  const upgradeBundle = buildBundle(upgrade);
  feedback(upgrade, upgradeBundle);
  check('injected write failure restores original bytes', () => { const before = readWiki(fix.wiki).wiki_root_sha256; assert.throws(() => install(upgrade.bundlePath, upgrade.feedbackPath, fix.wiki, { failAfter: 2 }), /Rolled back/); assert.equal(readWiki(fix.wiki).wiki_root_sha256, before); assert.equal(existsSync(join(fix.wiki, '.wiki-install.lock')), false); });
  check('upgrade succeeds after rollback', () => { const next = install(upgrade.bundlePath, upgrade.feedbackPath, fix.wiki); assert.equal(next.status, 'installed'); assert.equal(readWiki(fix.wiki).modules[0].lens_catalog.length, 2); });
  const changed = fixture(join(root, 'changed-source'));
  const changedBundle = buildBundle(changed); feedback(changed, changedBundle);
  writeFileSync(join(changed.root, 'source.md'), 'Changed source');
  check('source drift blocks installation', () => assert.throws(() => install(changed.bundlePath, changed.feedbackPath, changed.wiki), /Source changed|origin_hash_mismatch/));
  const changedSet = fixture(join(root, 'changed-set'));
  const setBundle = buildBundle(changedSet); feedback(changedSet, setBundle);
  changedSet.set.changes[0].object.question = 'Changed after review'; save(changedSet.changeSet, changedSet.set);
  check('proposal drift invalidates approval', () => assert.throws(() => install(changedSet.bundlePath, changedSet.feedbackPath, changedSet.wiki), /Change set changed/));
  const partial = fixture(join(root, 'partial'), { withRecipe: true });
  const partialBundle = buildBundle(partial);
  const partialApproval = feedback(partial, partialBundle);
  partialApproval.decisions = partialApproval.decisions.slice(0, 1); save(partial.feedbackPath, partialApproval);
  check('missing decisions require explicit partial mode', () => assert.throws(() => install(partial.bundlePath, partial.feedbackPath, partial.wiki), /Review invalid/));
  check('explicit partial mode installs only approved subset', () => { const subset = install(partial.bundlePath, partial.feedbackPath, partial.wiki, { approvedOnly: true }); assert.equal(subset.changes.length, 1); assert.equal(readWiki(partial.wiki).recipeCatalog.recipes.length, 0); });
  const blocked = fixture(join(root, 'blocked-recipe'), { withRecipe: true });
  const blockedBundle = buildBundle(blocked); const blockedApproval = feedback(blocked, blockedBundle);
  blockedApproval.decisions[0].decision = 'defer'; save(blocked.feedbackPath, blockedApproval);
  check('deferred required Lens blocks approved Recipe', () => assert.throws(() => install(blocked.bundlePath, blocked.feedbackPath, blocked.wiki), /Review invalid/));
  check('unknown origin mapping is rejected', () => { const value = structuredClone(blocked.set); value.sources[0].source_id = 'unknown'; assert.equal(validateChangeSet(value).valid, false); });
  check('zero candidates is a valid no-change conclusion', () => { const value = structuredClone(blocked.set); value.changes = []; assert.equal(validateChangeSet(value).valid, true); });
  const badVariant = fixture(join(root, 'bad-variant'), { withRecipe: true });
  badVariant.set.changes[1].object.steps[0].variant_id = 'variant_missing-method';
  save(badVariant.changeSet, badVariant.set);
  const badVariantBundle = buildBundle(badVariant); feedback(badVariant, badVariantBundle);
  check('missing Recipe Variant fails before any writes', () => {
    assert.throws(() => install(badVariant.bundlePath, badVariant.feedbackPath, badVariant.wiki), /Variant/);
    assert.equal(existsSync(badVariant.wiki), false);
  });
  const conflict = fixture(join(root, 'baseline-conflict'));
  conflict.wiki = fix.wiki; conflict.set.wiki_dir = fix.wiki; conflict.set.route = 'upgrade_existing';
  conflict.set.baseline_sha256 = readWiki(fix.wiki).wiki_root_sha256;
  conflict.set.modules = []; conflict.set.changes[0].object = lens('lens_conflict-proof');
  conflict.set.changes[0].comparison = { rationale_zh: '新的独立证据检验' };
  save(conflict.changeSet, conflict.set);
  const conflictBundle = buildBundle(conflict); feedback(conflict, conflictBundle);
  const oldIndex = readFileSync(join(fix.wiki, 'wiki-index.json'));
  const changedIndex = read(join(fix.wiki, 'wiki-index.json')); changedIndex.wiki_version = '9.0.0';
  save(join(fix.wiki, 'wiki-index.json'), changedIndex);
  check('library drift invalidates old approval without overwriting', () => {
    const before = readWiki(fix.wiki).wiki_root_sha256;
    assert.throws(() => install(conflict.bundlePath, conflict.feedbackPath, conflict.wiki), /changed since human review/);
    assert.equal(readWiki(fix.wiki).wiki_root_sha256, before);
  });
  writeFileSync(join(fix.wiki, 'wiki-index.json'), oldIndex);
  console.log(JSON.stringify({ suite: 'install', checks, valid: true }));
} finally { rmSync(root, { recursive: true, force: true }); }
